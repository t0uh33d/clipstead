import AppKit
import CryptoKit

public enum SkipReason: String, Sendable {
    case concealed, excludedApp, file, noText, empty, tooLarge, duplicate
}

public enum ClipboardDecision: Equatable, Sendable {
    case upload(String)
    /// The copy is an image (and has no text): read it with `NSPasteboard.imageSource`.
    case uploadImage
    case skip(SkipReason)
}

/// Decides whether a clipboard change should be uploaded. Pure logic, so it is unit-tested directly.
public struct ClipboardFilter: Sendable {
    /// Pasteboard types that password managers and other apps add to say "do not record this".
    /// Conventions from http://nspasteboard.org, plus 1Password's legacy marker.
    public static let privacyMarkers: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "de.petermaurer.TransientPasteboardType",
        "com.agilebits.onepassword",
    ]

    /// Image formats on the pasteboard that are synced as pictures when there is no text.
    public static let imageTypes: Set<String> = [
        "public.png", "public.tiff", "public.jpeg", "public.heic", "com.compuserve.gif",
    ]

    /// Password managers that are excluded until the user edits the list.
    public static let defaultExcludedApps = [
        "com.1password.1password",
        "com.agilebits.onepassword7",
        "com.bitwarden.desktop",
        "org.keepassxc.keepassxc",
        "com.apple.Passwords",
        "com.apple.keychainaccess",
    ]

    public var excludedApps: Set<String>
    public var maxBytes: Int

    public init(excludedApps: Set<String>, maxBytes: Int) {
        self.excludedApps = excludedApps
        self.maxBytes = maxBytes
    }

    /// `types` are the pasteboard's type identifiers and `sourceApp` is the frontmost app's bundle ID when the
    /// change was noticed. `text` is only called once every other check passes, so marked or excluded content is
    /// never read into this process.
    public func evaluate(types: Set<String>, sourceApp: String?, lastUploadedHash: String?, text: () -> String?) -> ClipboardDecision {
        if !types.isDisjoint(with: Self.privacyMarkers) { return .skip(.concealed) }
        if let sourceApp, excludedApps.contains(sourceApp) { return .skip(.excludedApp) }
        // Files copied in Finder: their names and icons are not clipboard content worth syncing.
        if types.contains("public.file-url") { return .skip(.file) }
        guard let value = text() else {
            return types.isDisjoint(with: Self.imageTypes) ? .skip(.noText) : .uploadImage
        }
        if value.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty { return .skip(.empty) }
        if value.utf8.count > maxBytes { return .skip(.tooLarge) }
        if Self.hash(value) == lastUploadedHash { return .skip(.duplicate) }
        return .upload(value)
    }

    public static func hash(_ text: String) -> String {
        hash(Data(text.utf8))
    }

    public static func hash(_ data: Data) -> String {
        SHA256.hash(data: data).map { String(format: "%02x", $0) }.joined()
    }
}

extension NSPasteboard {
    /// The type identifiers currently on the pasteboard. Reads no item data.
    public var typeIdentifiers: Set<String> {
        Set((types ?? []).map(\.rawValue))
    }

    /// The formatted version of the copied text, as HTML: the app's own HTML if it provided one (browsers do),
    /// otherwise RTF or RTFD converted to HTML (TextEdit, Pages, Notes, Word). Images and attachments are dropped.
    /// HTML is the one rich format a browser can put back on a clipboard. Call only after `ClipboardFilter` allows
    /// the copy.
    public var formattedHTML: String? {
        if let html = string(forType: .html), !html.isEmpty { return html }
        for type in [NSPasteboard.PasteboardType.rtf, .rtfd] {
            guard let data = data(forType: type) else { continue }
            let text = type == .rtf
                ? NSAttributedString(rtf: data, documentAttributes: nil)
                : NSAttributedString(rtfd: data, documentAttributes: nil)
            guard let text, text.length > 0,
                  let html = try? text.data(
                      from: NSRange(location: 0, length: text.length),
                      documentAttributes: [.documentType: NSAttributedString.DocumentType.html,
                                           .characterEncoding: String.Encoding.utf8.rawValue]
                  )
            else { continue }
            return String(data: html, encoding: .utf8)
        }
        return nil
    }
}
